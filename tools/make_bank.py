"""MIT: dsp/bank.h (generated, gitignored) from the committed sound pack assets/sounds/smp_bank.bin (default), a placeholder pack of original
generated tones (--placeholder; also what the core tests use), or user WAVs (--wav-dir: <name>.wav per instrument, mono PCM16 22050 Hz, root C4; missing ones stay placeholder)."""
import math, random, pathlib, wave, argparse, struct, sys
sys.path.insert(0,str(pathlib.Path(__file__).resolve().parent))
import adpcm
ROOT=pathlib.Path(__file__).resolve().parents[1]
NAMES='piano kick zip bell trumpet pulse dog cat pig horn baby guitar block organ bass piranha coin shyguy boo luigi peach feather bullet goomba bobomb spiny fruit oneup moon egg gnome'.split()
def tone(role,rng):
    if role in (15,16,17,18): # sustained, looped: 105-sample period (210 Hz), 20 periods, loop = the last 10
        w=[math.sin(2*math.pi*k/105)+(.4*math.sin(6*math.pi*k/105) if role&1 else .3*math.sin(4*math.pi*k/105)) for k in range(2100)]
        return dict(pcm=[round(v/1.6*20000*min(1,k/200)) for k,v in enumerate(w)],loop=(1050,2100),root=60)
    N=4096;samples=[];phase=0
    for i in range(N):
        t=i/22050;freq=261.625565
        if role==1:freq=55+160*math.exp(-t*35)
        elif role in (2,6,7,8,10):freq*=1+0.35*math.sin(t*(25+role*4))*math.exp(-t*9)
        elif role>14:freq*=2**(((role-19)%12-5)/12)
        phase+=2*math.pi*freq/22050
        s=math.sin(phase)
        if role in (0,3,11,12,14) or role in (19,22,25,28):s+=0.4*math.sin(phase*(2.01 if role==3 else 2))+0.15*math.sin(phase*4)
        elif role in (4,9,13) or role in (20,23,26,29):s+=0.4*math.sin(phase*3)+0.2*math.sin(phase*5)
        elif role==5 or role in (21,24,27,30):s=sum(math.sin(phase*k)/k for k in (1,3,5,7))
        elif role in (6,8,10):s=0.7*s+0.3*(rng.random()*2-1)
        env=min(1,i/64)*math.exp(-t*(8+role%5*3))*min(1,(N-1-i)/256)
        samples.append(round(max(-1,min(1,s*env/1.6))*28000))
    return dict(pcm=samples,root=60)
def main():
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--wav-dir',type=pathlib.Path);ap.add_argument('--placeholder',action='store_true');ap.add_argument('--bin',type=pathlib.Path,default=ROOT/'assets/sounds/smp_bank.bin');a=ap.parse_args()
    ph=a.placeholder or a.wav_dir
    if ph:
        rng=random.Random(100);insts=[]
        for role,name in enumerate(NAMES):
            t=tone(role,rng)
            if a.wav_dir and (a.wav_dir/(name+'.wav')).exists():
                with wave.open(str(a.wav_dir/(name+'.wav')),'rb') as w:
                    if (w.getnchannels(),w.getsampwidth(),w.getframerate())!=(1,2,22050):raise ValueError(name+': requires mono PCM16 22050Hz')
                    if not 2<=w.getnframes()<=65535:raise ValueError(name+': needs 2..65535 frames')
                    t=dict(pcm=list(struct.unpack('<'+'h'*w.getnframes(),w.readframes(w.getnframes()))),root=60)
            insts.append(t)
        blob=adpcm.pack(insts)
    else:blob=a.bin.read_bytes()
    ents,data,rate=adpcm.unpack(blob)
    text='/* Generated by tools/make_bank.py from %s (IMA ADPCM, %d Hz). */\nconst uint8_t sc_placeholder=%d;\nconst ScInst sc_inst[%d]={\n'%('a placeholder pack of generated tones' if ph else a.bin.name,rate,1 if ph else 0,len(ents))
    text+=',\n'.join('{%(off)d,%(frames)d,%(ls)d,%(le)d,%(lp)d,%(li)d,%(flags)d,%(root)d,%(scale)d,%(cents)d}'%e for e in ents)+'};\nconst uint8_t sc_adpcm[%d]={'%len(data)
    text+=','.join(map(str,data))+'};\n'
    (ROOT/'dsp/bank.h').write_text(text)
    print('bank: %d instruments, %d bytes ADPCM + %d table (%s)'%(len(ents),len(data),24*len(ents),'placeholder' if ph else a.bin.name))
if __name__=='__main__':main()
